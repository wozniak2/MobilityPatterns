  filter(has_rail == 1) %>%
  group_by(from_id, working_age_pop) %>%
  summarise(weighted_ratio = weighted.mean(x = time_ratio, w = workplaces)) %>%
  arrange(weighted_ratio) %>%
  ungroup() %>%
  mutate(sum_pop = cumsum(working_age_pop),
         rail = "rail")

