# Part 3 — most/moderately/least competitive itineraries by route
# =============================================================================
# Restyled version of a Google-Drive-only exploratory script
# (explore_travel_ratios.R) that predates this file's 2026-07-27 merge --
# see the "TBD" this replaces, just above.
#
# DATA SOURCE (revised 2026-08-31): the current pipeline's own
# itineraries_weights.csv/`itineraries` (Part 1's output, one row per OD
# pair) dropped the per-itinerary `route`/`mode` comma-joined strings that
# script's Part 3 read directly. A first attempt reconstructed route
# composition from pt_itineraries.rds's segment-level data instead -- ran
# fine, but produced visibly different routes than the original reference
# figure (caught by the user comparing screenshots), because it was
# necessarily built from a *different, more recent* itinerary run than
# whatever produced the original script's data -- not a styling bug, a
# wrong-source-data bug. The ACTUAL original itineraries_weights.csv (one
# row per itinerary, `route`/`mode` comma-joined per segment e.g.
# "0,KW,KW,0,158,0" -- "0" for legs with no route id, i.e. WALK) was
# recovered from Downloads/ and copied to
# itineraries_weights_route_detail.csv, used ONLY here -- Parts 1/2 above
# are untouched and still use the current pipeline's own `itineraries`.
itineraries_route_detail <- read.csv("itineraries_weights_route_detail.csv")
itineraries_route_detail$weight <- itineraries_route_detail$working_age_pop * itineraries_route_detail$workplaces

# Same three competitiveness bands and cutoffs as the original script
# (< 1.5 / 1.5-2.5 / >= 2.5, matching the `competitive`/`improvement`
# filters a few lines up) and the same `separate_longer_delim()` explode-
# by-comma approach. Deliberately NOT taking the top 30 here yet -- see
# the bug note below.
route_weights_by_band <- itineraries_route_detail %>%
  mutate(band = case_when(
    time_ratio < 1.5 ~ "Most competitive",
    time_ratio < 2.5 ~ "Moderately competitive",
    TRUE              ~ "Least competitive"
  ) %>% factor(levels = c("Most competitive", "Moderately competitive", "Least competitive"))) %>%
  select(route, weight, band) %>%
  separate_longer_delim(route, delim = ",") %>%
  group_by(band, route) %>%
  summarise(sum_weight = sum(weight), .groups = "drop")

# GTFS route shapes -- ZTM only (bus/tram operator; rail route codes have
# no shape here, see note above)
gtfs_ztm      <- read_gtfs("gtfs/ztm.zip")
routes_shapes <- shapes_as_sf(gtfs_ztm$shapes)
trips_ztm     <- as.data.frame(gtfs_ztm$trips) %>% distinct(route_id, .keep_all = TRUE)
routes_shapes <- right_join(routes_shapes, trips_ztm, by = "shape_id") %>%
  st_transform(4326)

poz     <- st_read("poz.gpkg", quiet = TRUE)  # core-city boundary -- the only one drawn (see
poz_wgs <- st_transform(poz, 4326)            # below), matching every other figure in the
                                               # manuscript. The individual surrounding-municipality
                                               # borders from ap.gpkg were drawn briefly (2026-08-31,
                                               # matching the original script's `roi` layer exactly)
                                               # but removed per explicit follow-up request -- too
                                               # busy/cluttered against the routes. ap.gpkg itself is
                                               # still used below for the ROI filter/map extent, just
                                               # not drawn.
ap      <- st_read("ap.gpkg", quiet = TRUE)   # full agglomeration (25 municipalities)
ap_wgs  <- st_transform(ap, 4326)
roi_wgs <- st_union(ap_wgs)                   # dissolved -- ROI filter/extent only, not drawn

# BUG FOUND 2026-08-31 (user compared this figure's routes against the
# faithful tmap replication and they didn't match, even though both read
# the identical recovered CSV): the top-30 selection MUST happen AFTER
# joining to real GTFS shapes and filtering to the ROI, not before. The
# original script's own order (left_join -> st_filter(roi) ->
# subset(!is.na(sum_weight)) -> THEN slice_max(n=30)) matters: "0" (the
# WALK-leg placeholder token, present in nearly every single itinerary)
# and "KW"/"IC" (rail operator codes, no shape in ztm.zip) accumulate
# enormous cumulative weight simply by being ubiquitous, so taking the
# top 30 on the raw exploded token table let them soak up slots that
# should have gone to real bus/tram routes -- they'd only get dropped
# LATER for not matching a route_id, by which point a real route ranked
# 31st+ never got considered. Fixed by reordering: join + ROI-filter
# first, slice_max() last.
routes_by_band <- routes_shapes %>%
  inner_join(route_weights_by_band, by = c("route_id" = "route")) %>%
  st_filter(roi_wgs, .predicate = st_intersects) %>%
  group_by(band) %>%
  slice_max(order_by = sum_weight, n = 30) %>%
  ungroup()

# Full ap.gpkg extent, matching the original script's (uncropped) framing --
# reverted 2026-08-31 from an earlier tight, city-centred crop. That crop
# was tuned against the WRONG reconstructed route data (see Part 3's data-
# source note above); the correct routes, verified against the original
# script's own tmap output, fill this full extent well on their own, no
# need to crop anything off.
map_limits_routes <- st_bbox(roi_wgs) %>% st_as_sfc() %>% st_buffer(0.02) %>% st_bbox()

# Dark basemap: inverted Esri grey canvas only (no Overpass road-network
# overlay -- removed 2026-08-31 per explicit request; the grey terrain/
# water texture stays, just without the added primary/secondary/tertiary
# road lines). NOT CartoDB.DarkMatter (used by Figs 3/5/8) -- CARTO's free
# tile tier now requires an API key for anonymous requests (confirmed
# 2026-08-28, see README). Fetched at map_limits_routes -- the full
# ap.gpkg extent (see above) -- so resolution matches what's actually shown.
bbox_routes_3857 <- map_limits_routes %>% st_as_sfc() %>% st_transform(3857)
osm_tiles_routes <- get_tiles(bbox_routes_3857, provider = "Esri.WorldGrayCanvas", zoom = 11, crop = TRUE)
osm_bw_routes <- app(osm_tiles_routes, fun = function(x) {
  grey <- 0.299 * x[1] + 0.587 * x[2] + 0.114 * x[3]
  255 - grey
})
osm_bw_routes <- c(osm_bw_routes, osm_bw_routes, osm_bw_routes)

# Panel colours reuse Figure 5's PT-vs-car palette (09_OD_comparison.R:
# green = PT/competitive end, orange = intermediate, red = car-dominated
# end) for cross-figure consistency, rather than picking new colours.
band_colours_routes <- c(
  "Most competitive"       = "#2ecc71",
  "Moderately competitive" = "#e67e22",
  "Least competitive"      = "#c0392b"
)

make_route_competitiveness_map <- function(routes_sf, band_label) {
  ggplot() +
    geom_spatraster_rgb(data = osm_bw_routes, alpha = 0.75) +
    # Core-city (poz.gpkg) boundary only -- matches every other figure in
    # the manuscript. Drawing all 25 ap.gpkg municipal boundaries (matching
    # the original script's `roi` layer exactly) was tried first but
    # removed per explicit follow-up request (too cluttered).
    geom_sf(data = poz_wgs, fill = NA, colour = "white",
            linewidth = 0.4, inherit.aes = FALSE) +
    geom_sf(data = routes_sf, colour = band_colours_routes[[band_label]],
            linewidth = 0.9, alpha = 0.9, inherit.aes = FALSE) +
    coord_sf(crs = 4326, xlim = map_limits_routes[c("xmin", "xmax")],
             ylim = map_limits_routes[c("ymin", "ymax")]) +
    # Wrapped onto two lines rather than tuned to fit one -- a one-line
    # title at a legible size kept colliding with its neighbour whenever
    # patchwork's column widths shifted (e.g. when a fixed-aspect coord_sf
    # panel's actual rendered width changed, found 2026-08-28); a short
    # two-line title is robust to that regardless of exact column width.
    labs(title = paste0(band_label, " itineraries,\n30 top bus routes")) +
    theme_dark(base_size = 18) +
    theme(
      panel.background = element_rect(fill = "#1a1a1a"),
      plot.background  = element_rect(fill = "#1a1a1a", colour = NA),
      text             = element_text(color = "white"),
      axis.text        = element_blank(),
      axis.title       = element_blank(),
      axis.ticks       = element_blank(),
      axis.line        = element_blank(),
      panel.grid.major = element_blank(),
      panel.grid.minor = element_blank(),
      panel.border     = element_blank(),
      # Title size increased 14 -> 20 and bolded per explicit request (2026-08-28).
      # Canvas widened to match (see ggsave below) -- at the old width=16 canvas,
      # size 22 titles overlapped between panels; still touched at the panel
      # edges at width=22 with no margin, so a small left/right plot.margin
      # gutter was added too. Tightened r/l 10 -> 2 per explicit follow-up
      # request (2026-08-31) for thinner spacing between panels -- titles are
      # now wrapped to two short lines (see labs(title=) above), so they no
      # longer need much horizontal breathing room to avoid colliding.
      plot.title       = element_text(size = 18, face = "bold", color = "white", hjust = 0.5, lineheight = 0.95),
      plot.margin      = margin(t = 5, r = 2, b = 5, l = 2)
    )
}

band_levels_routes <- levels(routes_by_band$band)
band_maps_routes <- setNames(lapply(band_levels_routes, function(b) {
  make_route_competitiveness_map(routes_by_band %>% filter(band == b), b)
}), band_levels_routes)

